"""Deterministic Grounding, Reflection, and Verification Engine for Agentic DataPilot.

Inspects candidate answers against ground-truth MCP tool evidence,
recalculates arithmetic deterministically in Python, and detects
unsupported claims or contradictions.
"""

from __future__ import annotations

import re
from typing import Any, Dict, List, Optional, Set
from pydantic import BaseModel, Field

from agent.evidence import EvidenceRecord


class VerificationResult(BaseModel):
    """Structured result of grounded answer verification."""

    is_verified: bool = Field(description="True if all claims are grounded in tool evidence.")
    confidence_score: float = Field(description="Numerical confidence between 0.0 and 1.0.")
    verified_claims: List[str] = Field(default_factory=list)
    unsupported_claims: List[str] = Field(default_factory=list)
    contradictions: List[str] = Field(default_factory=list)
    missing_evidence: List[str] = Field(default_factory=list)
    recalculated_metrics: Dict[str, Any] = Field(default_factory=dict)
    feedback_for_correction: Optional[str] = None
    explanation: str = Field(description="Human-readable explanation of the verification outcome.")


class AnswerVerifier:
    """Performs deterministic verification of LLM-generated answers against evidence."""

    @staticmethod
    def _extract_numbers(text: str) -> List[float]:
        """Extract monetary or numeric values from text, ignoring commas and dollar signs."""
        # Match currency numbers like $68,400.00 or standalone numbers like 68400
        pattern = r"\$?\s*([0-9]{1,3}(?:,[0-9]{3})*(?:\.[0-9]+)?|[0-9]+(?:\.[0-9]+)?)"
        matches = re.findall(pattern, text)
        numbers = []
        for m in matches:
            cleaned = m.replace(",", "").strip()
            try:
                val = float(cleaned)
                # Ignore trivial numbers like 0, 1, 2, 2024 (years/dates)
                if val not in [0.0, 1.0, 2.0, 2024.0, 2025.0, 2026.0]:
                    numbers.append(val)
            except ValueError:
                continue
        return numbers

    @staticmethod
    def _extract_percentages(text: str) -> List[float]:
        """Extract percentage figures from text (e.g., 54.05%, +54.1%)."""
        pattern = r"([+-]?[0-9]+(?:\.[0-9]+)?)\s*%"
        matches = re.findall(pattern, text)
        percentages = []
        for m in matches:
            try:
                percentages.append(float(m))
            except ValueError:
                continue
        return percentages

    @classmethod
    def verify(
        cls,
        candidate_answer: str,
        evidence: EvidenceRecord,
        user_query: Optional[str] = None,
    ) -> VerificationResult:
        """Verify candidate answer claims against the structured evidence record.

        Args:
            candidate_answer: The proposed text answer generated by the agent.
            evidence: The EvidenceRecord containing facts collected from MCP tools.
            user_query: The original question (optional context).

        Returns:
            VerificationResult with detailed breakdown of verified claims and discrepancies.
        """
        if not candidate_answer or not candidate_answer.strip():
            return VerificationResult(
                is_verified=False,
                confidence_score=0.0,
                explanation="Candidate answer is empty.",
                missing_evidence=["No answer content provided."],
            )

        # 1. Extract potential empirical claims
        extracted_nums = cls._extract_numbers(candidate_answer)
        extracted_pcts = cls._extract_percentages(candidate_answer)
        answer_lower = candidate_answer.lower()
        mentioned_products = [
            prod for prod in evidence.known_products
            if prod.lower() in answer_lower
        ]

        # If answer contains no numerical figures, percentages, or product claims (e.g. greeting/help)
        if not extracted_nums and not extracted_pcts and not mentioned_products:
            return VerificationResult(
                is_verified=True,
                confidence_score=1.0,
                explanation="Answer contains no numerical or dataset-specific claims (conversational/informational response).",
                verified_claims=["Conversational response with zero ungrounded claims."],
            )

        # 2. Check if any evidence was gathered to support the data claims
        if not evidence.facts and not evidence.raw_observations:
            return VerificationResult(
                is_verified=False,
                confidence_score=0.0,
                missing_evidence=["No MCP tools were executed; zero observations exist to support claims."],
                feedback_for_correction="No tool evidence was gathered. You must call an appropriate MCP tool to inspect the dataset before formulating an answer.",
                explanation="Verification failed: The agent made numerical or product claims without gathering evidence from MCP tools.",
            )

        verified_claims: List[str] = []
        unsupported_claims: List[str] = []
        contradictions: List[str] = []
        recalculated: Dict[str, Any] = {}

        # 2. Extract facts from evidence
        observed_numbers: Dict[float, str] = {}
        observed_percentages: Dict[float, str] = {}
        observed_top_products: Set[str] = set()

        for f in evidence.facts:
            if f.numeric_value is not None:
                if f.fact_type == "percentage_growth":
                    observed_percentages[round(f.numeric_value, 2)] = (
                        f"Growth for {f.subject} ({f.numeric_value:+.2f}%) from {f.source_tool}"
                    )
                else:
                    observed_numbers[round(f.numeric_value, 2)] = (
                        f"{f.fact_type} for {f.subject} (${f.numeric_value:,.2f}) from {f.source_tool}"
                    )
            if f.fact_type == "top_product" and f.string_value:
                observed_top_products.add(f.string_value.lower())

        # 3. Check Product Identity & Top Product assertion
        answer_lower = candidate_answer.lower()
        mentioned_products = [
            prod for prod in evidence.known_products
            if prod.lower() in answer_lower
        ]

        if observed_top_products:
            # Check if an actual top product is mentioned
            correct_top_mentioned = any(tp in answer_lower for tp in observed_top_products)
            if correct_top_mentioned:
                matching_prods = [tp for tp in observed_top_products if tp in answer_lower]
                verified_claims.append(f"Correctly identified top product: {matching_prods}")
            else:
                # Check if a different product was asserted
                if mentioned_products:
                    contradictions.append(
                        f"Answer mentions product(s) {mentioned_products}, but actual top product in evidence is {list(observed_top_products)}."
                    )
                else:
                    unsupported_claims.append(
                        f"Failed to identify verified top product: {list(observed_top_products)}"
                    )

        # 4. Check Percentage Claims against Ground Truth
        extracted_pcts = cls._extract_percentages(candidate_answer)
        for pct in extracted_pcts:
            rounded_pct = round(pct, 2)
            matched = False
            for obs_pct, desc in observed_percentages.items():
                if abs(rounded_pct - obs_pct) <= 0.2:  # allow slight rounding tolerance e.g. 54.05 vs 54.1
                    verified_claims.append(f"Verified percentage {pct}% matches: {desc}")
                    matched = True
                    break
            if not matched:
                # Recalculate against period comparisons if available
                recalc_found = False
                for comp in evidence.period_comparisons:
                    rev_a = comp.get("period_a", {}).get("total_revenue", 0.0)
                    rev_b = comp.get("period_b", {}).get("total_revenue", 0.0)
                    if rev_a > 0:
                        true_pct = round(((rev_b - rev_a) / rev_a) * 100.0, 2)
                        recalculated[f"growth_{comp.get('product')}"] = true_pct
                        if abs(rounded_pct - true_pct) <= 0.2:
                            verified_claims.append(f"Verified percentage {pct}% matches recalculated growth ({true_pct}%)")
                            recalc_found = True
                            break
                        else:
                            contradictions.append(
                                f"Claimed growth {pct}% contradicts recalculated arithmetic {true_pct}% from ${rev_a:,.2f} to ${rev_b:,.2f}."
                            )
                            recalc_found = True
                            break
                if not recalc_found:
                    unsupported_claims.append(f"Percentage {pct}% is not substantiated by any tool observation.")

        # 5. Check Numeric Claims against Ground Truth
        extracted_nums = cls._extract_numbers(candidate_answer)
        for num in extracted_nums:
            rounded_num = round(num, 2)
            matched = False
            for obs_num, desc in observed_numbers.items():
                if abs(rounded_num - obs_num) <= 1.0:  # within $1.00 tolerance
                    verified_claims.append(f"Verified numerical figure ${num:,.2f} matches {desc}")
                    matched = True
                    break
            if not matched:
                # Check if it was one of the percentage numbers mistakenly extracted
                if any(abs(rounded_num - round(p, 2)) < 0.01 for p in extracted_pcts):
                    continue
                unsupported_claims.append(
                    f"Number {num:,.2f} does not match any revenue, order count, or difference in evidence."
                )

        # 6. Overall Verification Decision
        has_critical_failures = bool(contradictions or unsupported_claims)
        total_claims = len(verified_claims) + len(unsupported_claims) + len(contradictions)
        confidence = (
            round(len(verified_claims) / total_claims, 2)
            if total_claims > 0
            else 0.0
        )

        is_verified = (not has_critical_failures) and (len(verified_claims) >= 1)

        if is_verified:
            explanation = "All key entities, metrics, and numerical figures are grounded and verified against MCP tool observations."
            feedback = None
        else:
            explanation = "Answer failed grounding verification due to contradictions or unsupported numbers."
            feedback_parts = []
            if contradictions:
                feedback_parts.append("Contradictions detected: " + "; ".join(contradictions))
            if unsupported_claims:
                feedback_parts.append("Unsupported claims: " + "; ".join(unsupported_claims))
            feedback_parts.append("Established ground-truth facts:\n" + evidence.get_summary_text())
            feedback_parts.append("Please revise the answer to use only the exact ground-truth facts above.")
            feedback = "\n".join(feedback_parts)

        return VerificationResult(
            is_verified=is_verified,
            confidence_score=confidence,
            verified_claims=verified_claims,
            unsupported_claims=unsupported_claims,
            contradictions=contradictions,
            missing_evidence=[],
            recalculated_metrics=recalculated,
            feedback_for_correction=feedback,
            explanation=explanation,
        )
